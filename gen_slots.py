"""Write slots.h: the method names of each hooked COM interface in vtable order.

Usage: python3 gen_slots.py <mingw include folder>
"""
import re
import sys

INTERFACES = [
    ("d3d12.h", "ID3D12Device10", "device"),
    ("d3d12.h", "ID3D12CommandQueue", "queue"),
    ("dxgi1_6.h", "IDXGIFactory7", "factory"),
    ("dxgi1_6.h", "IDXGIAdapter4", "adapter"),
    ("dxgi1_6.h", "IDXGIOutput6", "output"),
    ("dxgi1_5.h", "IDXGISwapChain4", "swapchain"),
]


def method_names(include, header, interface):
    text = open(f"{include}/{header}").read()
    body = re.search(rf"typedef struct {interface}Vtbl \{{(.*?)\}} {interface}Vtbl;", text, re.S)
    return re.findall(r"\(STDMETHODCALLTYPE \*(\w+)\)", body.group(1))


def main():
    include = sys.argv[1]
    lines = ["/* Generated by gen_slots.py from the mingw headers. Do not edit. */"]
    for header, interface, name in INTERFACES:
        names = method_names(include, header, interface)
        lines.append(f"static const char *const {name}_methods[] =\n{{")
        lines.extend(f'    "{method}",' for method in names)
        lines.append("};")
        lines.append(f"#define {name.upper()}_METHOD_COUNT {len(names)}")
    open("slots.h", "w").write("\n".join(lines) + "\n")


main()
